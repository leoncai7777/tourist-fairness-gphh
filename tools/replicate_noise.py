"""
How many replicates a validation (and test) day needs (F1, K)
=============================================================

Takes up to ten distinct front rules of each method's full pilot run, spread
from one end of the front to the other, and scores each on the 35 validation
days with replicates 0 to 4, keeping both objectives of every day and
replicate. Then:

  - the spread between replicates of one rule on one day, for mean R_v and
    G_hat (sample standard deviation over the 5 replicates);
  - the standard error of a rule's validation mean due to the replicates only
    (the 35 days are fixed):  SE_K = sqrt( mean over days of s_d^2 / (35 K) ),
    s_d the spread on day d. K = 5 is what was run; K = 1 and 3 are also taken
    directly from the first replicates; K = 10 is computed from the spread
    only, as nothing was run with 10;
  - how far the means with K = 1 and 3 replicates are from those with 5;
  - the distance between neighbouring sampled rules (ten spread along the front, so much wider
    than between adjacent front rules, which are 0.0006 to 0.005 apart in mean R_v).

Training and validation days only. Kept in tools/, outside the code version.

Run:  python3 tools/replicate_noise.py   (from the repository root)
Writes outputs/search/pilot/replicates/record.md.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from evaluate import evaluate  # noqa: E402
from gp_rule import from_text  # noqa: E402
from search import DEFINITIONS, complete, days_for, scoring, validation_dates  # noqa: E402

PILOT = ROOT / "outputs" / "search" / "pilot" / "full"
OUT = ROOT / "outputs" / "search" / "pilot" / "replicates"
RULES_PER_FRONT, K = 10, 5


def main():
    settings = complete({"population": 200, "generations": 100, "crossover": 0.8, "mutation": 0.15,
                         "monitor every": 10, "validation replicates": K})
    days, options, dates = days_for(settings), scoring(settings), validation_dates()
    rows = []
    for front_file in sorted(PILOT.glob("*/results/front.csv.gz")):
        method = front_file.parts[-3].rsplit("_", 1)[0]
        front = pd.read_csv(front_file).drop_duplicates("text").sort_values("G_hat").reset_index(drop=True)
        picks = np.unique(np.linspace(0, len(front) - 1, min(RULES_PER_FRONT, len(front))).round().astype(int))
        for i in picks:
            rule = from_text(front.loc[i, "text"])
            for date in dates:
                for r in range(K):
                    result = evaluate(rule, date, r, days, **options)
                    rows.append((method, front.loc[i, "rule"], date, r, result.mean_r, result.g_hat))
    t = pd.DataFrame(rows, columns=["method", "rule", "date", "replicate", "R", "G"])

    lines = ["# Replicates per validation day (K)", "",
             f"Up to {RULES_PER_FRONT} distinct front rules of each method's full pilot run (run 910), spread along "
             f"the front; 35 validation days, replicates 0 to {K - 1}; definitions {DEFINITIONS}. "
             "Generated by `tools/replicate_noise.py`.", "",
             "SE_K = sqrt(mean over days of s_d^2 / (35 K)), s_d the sample standard deviation of the 5 replicates "
             "of a rule on day d: the error of a rule's validation mean due to the replicates only, the days being "
             "fixed. K = 5 was run; K = 1 and 3 are also taken directly from replicates 0 and 0-2; **K = 10 is "
             "computed from the spread, not run.** Medians over the rules.", "",
             "| Method | Rules | Objective | Spread within a day (median) | SE, K = 1 | SE, K = 3 | SE, K = 5 "
             "| SE, K = 10 (computed) | Largest gap to K = 5 mean, K = 1 | K = 3 | Gap between neighbouring "
             "sampled rules (median) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for method, g in t.groupby("method"):
        for objective in ("R", "G"):
            spread = g.groupby(["rule", "date"])[objective].std(ddof=1)
            variance = (spread ** 2).groupby(level="rule").mean()
            se = {k: float(np.sqrt(variance / (35 * k)).median()) for k in (1, 3, 5, 10)}
            full = g.groupby("rule")[objective].mean()
            gap = {k: float((g[g["replicate"] < k].groupby("rule")[objective].mean() - full).abs().max())
                   for k in (1, 3)}
            neighbours = float(np.median(np.diff(np.sort(full.values))))
            name = "mean R_v" if objective == "R" else "G_hat"
            lines.append(f"| {method} | {g['rule'].nunique()} | {name} | {spread.median():.4f} | {se[1]:.4f} | "
                         f"{se[3]:.4f} | {se[5]:.4f} | {se[10]:.4f} | {gap[1]:.4f} | {gap[3]:.4f} | {neighbours:.4f} |")
    lines.append("")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "record.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
